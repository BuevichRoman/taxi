/**
 * Часы сервера (ТЗ п. 4).
 *
 * ТЗ запрещает брать отметки времени с устройства: часы няни могут врать на
 * минуты, а из них считается оплачиваемое время и стоимость заказа.
 *
 * Отдельной ручки «который час» у API нет, но серверное время приходит в
 * каждом ответе — в заголовке `Date`, он обязателен по RFC 7231. По нему
 * считается смещение часов устройства, и дальше время идёт от исправленного.
 *
 * Когда заголовок доступен браузеру:
 *
 * - приложение отдаётся с того же origin, что и API — читается всегда;
 * - иначе нужен ответный `Access-Control-Expose-Headers: Date`. Сейчас боевой
 *   отдаёт `Access-Control-Allow-Origin: *`, но список открытых заголовков не
 *   шлёт, поэтому с чужого origin `Date` браузеру не виден.
 *
 * Пока ни одного ответа не пришло или заголовок недоступен, смещение нулевое —
 * то есть прежнее поведение, часы устройства. Механизм ничего не ломает в том
 * окружении, где не работает.
 *
 * Точности хватает: заголовок с точностью до секунды, к этому добавляется
 * задержка сети в одну сторону, а оплачиваемое время округляется до минуты.
 *
 * Чего это не заменяет: серверной отметки самой записи. Пока перерыв пишет
 * клиент действием `edit`, момент проставляет он же — просто теперь по
 * исправленным часам. Отметку, проставленную сервером, даст только серверная
 * реализация записи (ТЗ п. 14).
 */
import axios from 'axios'

let offsetMs = 0

/** Смещение часов устройства относительно сервера, миллисекунды */
export const serverOffsetMs = (): number => offsetMs

/** Текущее время сервера */
export const serverNow = (): Date => new Date(Date.now() + offsetMs)

/**
 * Учесть заголовок `Date` ответа.
 *
 * Значение разбирает `Date.parse`: формат заголовка жёстко задан стандартом,
 * разночтений между браузерами здесь нет — в отличие от даты через пробел,
 * которая ходит в теле запросов.
 */
export const syncFromHttpDate = (value?: string | null): void => {
  if (!value) return

  const serverMs = Date.parse(value)

  if (Number.isNaN(serverMs)) return

  offsetMs = serverMs - Date.now()
}

/** Только для тестов: вернуть часы к состоянию «ответов ещё не было» */
export const resetServerClock = (): void => {
  offsetMs = 0
}

/**
 * Подписаться на ответы API. Вызывается один раз при старте приложения.
 * Перехватчик стоит на общем экземпляре axios — через него идут все вызовы.
 */
export const installServerClock = (): void => {
  axios.interceptors.response.use(
    response => {
      syncFromHttpDate(response.headers?.date)

      return response
    },
    error => {
      // Ошибочный ответ тоже несёт заголовок, а обрыв связи — нет
      syncFromHttpDate(error?.response?.headers?.date)

      return Promise.reject(error)
    },
  )
}
